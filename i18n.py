TABLES = {"pt": PT, "es": ES, "fr": FR, "de": DE, "it": IT, "ja": JA, "zh": ZH}
lang = "en"


def detect(ui_languages):
    """Primeiro idioma da lista do sistema que o Lume conhece; LUME_LANG (en, pt, es...) forca um."""
    forced = os.environ.get("LUME_LANG", "").lower()[:2]
    if forced:
        return forced if forced in TABLES else "en"
    for code in ui_languages:
        short = code.lower()[:2]
        if short == "en" or short in TABLES:
            return short
    return "en"


def set_lang(code):
    global lang
    lang = code


def table():
    return TABLES.get(lang, {})


def _(text):
    return table().get(text, text)
